library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use IEEE.NUMERIC_STD.ALL;

entity text_display is
    port (
        clk       : in  std_logic;
        text_type : in  std_logic_vector(1 downto 0);  -- 00: SCORE, 01: HIGH, 10: LEVEL
        x_pos     : in  std_logic_vector(5 downto 0);  -- 0-39，文本内的水平位置
        y_pos     : in  std_logic_vector(2 downto 0);  -- 0-7，文本内的垂直位置
        pixel_on  : out std_logic                      -- 当前像素是否点亮
    );
end text_display;

architecture Behavioral of text_display is
    -- 文本位图常量 (S C O R E)
    type text_bitmap is array(0 to 7) of std_logic_vector(39 downto 0);
    constant SCORE_TEXT : text_bitmap := (
        "0001111000111100001111000111100001111000", -- .****..****..****..****..****..
        "0110001101000010010000100100001001000000", -- **...**..**..*...**.*..**..*...
        "0110000001000000010000000100000001000000", -- **......**......**......**..*.
        "0001111000111100001111000111110001111000", -- .****..****..****..*****.****..
        "0000001100000010000000100100001001000000", -- ....**....**......**.*..**..*..
        "0000001101000010010000100100001001000000", -- ....**.*..**..*...**.*..**..*..
        "0110001101000010010000100100001001000000", -- **...**..**..*...**.*..**..*...
        "0001111000111100001111000111100001111000"  -- .****..****..****..****..****..
    );
    
    constant HIGH_TEXT : text_bitmap := (
        "0110001100111110001111000110001100000000", -- **...**.*****..****..**..**......
        "0110001101000010010000100110001100000000", -- **...**..**..*...**.**...**......
        "0110001101000000010000000110001100000000", -- **...**..**..*........**...**....
        "0111111001111100001111000111111000000000", -- ******.*****..****..******......
        "0110001101000000010000000110001100000000", -- **...**..**..........**...**....
        "0110001101000000010000000110001100000000", -- **...**..**..........**...**....
        "0110001101000010010000100110001100000000", -- **...**..**..*...**.**...**......
        "0110001100111110001111000110001100000000"  -- **...**.*****..****..**..**......
    );
    
    constant LEVEL_TEXT : text_bitmap := (
        "0110000000111110011111000110001100000000", -- **......*****.*****.**...**....
        "0110000001000010010000100110001100000000", -- **......*..*..*..**.**...**....
        "0110000001000000010000000110001100000000", -- **......*........**.**...**....
        "0110000001000000011111000111111000000000", -- **......*.....*****.*****....
        "0110000001000000010000000110001100000000", -- **......*........**.**...**....
        "0110000001000000010000000110001100000000", -- **......*........**.**...**....
        "0111111001000010010000100110001100000000", -- ******.*..*..*..**.**...**....
        "0111111000111110011111000110001100000000"  -- ******.****.*****.**...**....
    );
    
    signal bitmap : std_logic;
begin
    process(clk)
        variable x_idx : integer range 0 to 39;
        variable y_idx : integer range 0 to 7;
    begin
        if rising_edge(clk) then
            x_idx := to_integer(unsigned(x_pos));
            y_idx := to_integer(unsigned(y_pos));
            
            case text_type is
                when "00" =>  -- SCORE
                    pixel_on <= SCORE_TEXT(y_idx)(39 - x_idx);
                when "01" =>  -- HIGH
                    pixel_on <= HIGH_TEXT(y_idx)(39 - x_idx);
                when "10" =>  -- LEVEL
                    pixel_on <= LEVEL_TEXT(y_idx)(39 - x_idx);
                when others =>
                    pixel_on <= '0';
            end case;
        end if;
    end process;
end Behavioral; 